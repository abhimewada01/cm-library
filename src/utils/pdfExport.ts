import { Platform } from 'react-native';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';

/** Opens a print-to-PDF flow in browsers and shares a real generated PDF file on native. */
export async function exportHtmlAsPdf(html: string, fileName: string) {
  if (Platform.OS === 'web') {
    const frame = document.createElement('iframe');
    frame.setAttribute('title', `Print ${fileName}`);
    Object.assign(frame.style, {
      position: 'fixed', inset: '0', width: '100vw', height: '100vh',
      border: '0', opacity: '0', pointerEvents: 'none', zIndex: '-1',
    });
    document.body.appendChild(frame);

    const frameWindow = frame.contentWindow;
    const frameDocument = frame.contentDocument;
    if (!frameWindow || !frameDocument) {
      frame.remove();
      throw new Error('Could not prepare the print view. Please try again.');
    }

    let started = false;
    const cleanup = () => window.setTimeout(() => frame.remove(), 1000);
    frameWindow.addEventListener('afterprint', cleanup, { once: true });
    const printWhenReady = async () => {
      if (started) return;
      started = true;
      await Promise.all(Array.from(frameDocument.images).map(image => image.complete
        ? Promise.resolve()
        : new Promise<void>(resolve => {
          image.addEventListener('load', () => resolve(), { once: true });
          image.addEventListener('error', () => resolve(), { once: true });
        })));
      await frameDocument.fonts?.ready;
      window.setTimeout(() => {
        frameWindow.focus();
        frameWindow.print();
      }, 150);
    };
    frame.onload = () => { void printWhenReady(); };
    frameDocument.open();
    frameDocument.write(html.replace('</head>', `<title>${escapeHtml(fileName)}</title></head>`));
    frameDocument.close();
    // Some embedded browsers do not dispatch iframe.onload after document.write.
    window.setTimeout(() => { void printWhenReady(); }, 500);
    window.setTimeout(() => frame.remove(), 120_000);
    return;
  }

  const file = await Print.printToFileAsync({ html });
  const canShare = await Sharing.isAvailableAsync();
  if (!canShare) throw new Error('PDF created, but file sharing is not available on this device.');
  await Sharing.shareAsync(file.uri, {
    mimeType: 'application/pdf',
    dialogTitle: `Save ${fileName}`,
    UTI: 'com.adobe.pdf',
  });
}

export function escapeHtml(value: unknown) {
  return String(value ?? '').replace(/[&<>"']/g, (character) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  })[character] ?? character);
}

